    ];

    /**
     * The codes a foreign number may carry: every country except Sweden.
     *
     * @return list<string>
     */
    public static function foreign(): array
    {
        return array_values(array_diff(self::CODES, ['SE']));
    }

    public static function isForeign(?string $code): bool
    {
        return $code !== null && in_array($code, self::foreign(), true);
    }

    public static function name(string $code): string
    {
        $name = Locale::getDisplayRegion('-'.$code, app()->getLocale());

        return is_string($name) && $name !== '' ? $name : $code;
    }

    /**
     * Foreign countries for a select, sorted by name in the user's language.
     *
     * @return array<string, string> code => name
     */
    public static function options(): array
    {
        $options = [];

        foreach (self::foreign() as $code) {
            $options[$code] = self::name($code);
        }

        (new Collator(app()->getLocale()))->asort($options);

        return $options;
    }
}
